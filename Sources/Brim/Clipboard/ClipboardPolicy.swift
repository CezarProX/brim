// ClipboardPolicy.swift
// Brim
//
// Pure rules for what the clipboard history records and keeps: privacy filters,
// duplicate handling, retention by age and count. The store applies them; tests pin them.

import Foundation

struct ClipboardPolicy: Equatable, Sendable {
    /// Maximum entries, or nil for "no limit" (the 100 MB size cap still applies).
    var limit: Int?
    var keepFor: ClipboardKeepFor = .forever
    var rejectDuplicates = true
    var skipSensitive = true
    var excludedApps: Set<String> = []
    var cleanLinksOnCapture = false
    var cleanLinksOnCopy = true

    init() { limit = 100 }

    init(settings: AppSettings) {
        let value = settings.clipboardHistoryLimit
        limit = value > 0 ? value : nil
        keepFor = settings.clipboardKeepFor
        rejectDuplicates = settings.clipboardRejectDuplicates
        skipSensitive = settings.clipboardSkipPasswords
        excludedApps = Set(settings.clipboardExcludedApps)
        cleanLinksOnCapture = settings.clipboardCleanLinksOnCapture
        cleanLinksOnCopy = settings.clipboardCleanLinksOnCopy
    }

    // MARK: Privacy

    /// Pasteboard types that mark an item as secret or not worth keeping.
    private static let sensitiveTypeMarkers: Set<String> = [
        "org.nspasteboard.concealedtype", "org.nspasteboard.transienttype",
        "org.nspasteboard.autogeneratedtype", "com.agilebits.onepassword",
        "de.petermaurer.transientpasteboardtype", "com.typeit4me.clipping", "pasteboard generator type",
    ]
    /// Brim's own markers: never recorded, whatever the privacy settings.
    private static let ownTypeMarkers: Set<String> = [
        "org.nspasteboard.restoredtype", "io.github.cezarprox.brim.screenshot", "io.github.cezarprox.brim.clipboard-replay",
    ]
    /// Bundle identifiers of password managers (lowercased).
    static let passwordManagers: Set<String> = [
        "com.1password.1password", "com.1password.1password7", "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx", "com.agilebits.onepassword4", "com.bitwarden.desktop",
        "org.keepassxc.keepassxc", "com.dashlane.dashlanephonefinal", "com.lastpass.lastpass",
        "io.enpass.mac", "com.apple.passwords", "com.apple.keychainaccess", "me.proton.pass.electron",
        "com.nordsec.nordpass", "com.mseven.msecure", "com.stickypassword.stickypasswordmac",
    ]

    /// True when the types or the app that wrote them mark the copy as sensitive.
    static func isSensitive(types: [String], frontmost: String?) -> Bool {
        if let frontmost, passwordManagers.contains(frontmost.lowercased()) { return true }
        return types.contains { type in
            let value = type.lowercased()
            return sensitiveTypeMarkers.contains(value) || value.contains("password") || value.contains("concealed")
        }
    }

    /// True when this copy must not enter history.
    func shouldSkip(types: [String], frontmost: String?) -> Bool {
        if types.contains(where: { Self.ownTypeMarkers.contains($0.lowercased()) }) { return true }
        if let frontmost, excludedApps.contains(frontmost) { return true }
        return skipSensitive && Self.isSensitive(types: types, frontmost: frontmost)
    }

    // MARK: Retention

    /// The entries to keep, pinned first then newest first. Unpinned entries older than `keepFor`
    /// are dropped, the count is capped at `limit`, and the running byte total stays within `maxBytes`.
    /// Never mutates its input.
    static func retain(_ candidates: [ClipboardEntry], now: Date = Date(), limit: Int, maxBytes: Int,
                       keepFor: ClipboardKeepFor) -> [ClipboardEntry] {
        let cutoff = keepFor.maxAge.map { now.addingTimeInterval(-$0) }
        let newestFirst: (ClipboardEntry, ClipboardEntry) -> Bool = { $0.date > $1.date }
        let alive = candidates.filter { entry in
            entry.isPinned || cutoff.map { entry.date >= $0 } ?? true
        }
        let ordered = alive.filter(\.isPinned).sorted(by: newestFirst)
            + alive.filter { !$0.isPinned }.sorted(by: newestFirst)
        var bytes = 0
        var retained: [ClipboardEntry] = []
        for entry in ordered where retained.count < limit {
            guard entry.byteCount <= maxBytes - bytes else { continue }
            bytes += entry.byteCount
            retained.append(entry)
        }
        return retained
    }

    /// Library order: pinned entries first (optionally), each group newest first.
    static func displayOrder<T>(_ items: [T], date: (T) -> Date, pinned: (T) -> Bool,
                                placement: ClipboardPinnedPlacement) -> [T] {
        let sorted = items.sorted { date($0) > date($1) }
        guard placement == .beforeRecent else { return sorted }
        return sorted.filter(pinned) + sorted.filter { !pinned($0) }
    }
}
