import AppKit
import Testing
@testable import Brim

@MainActor
struct ClipboardStoreTests {
    private func directory() -> URL { FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString) }
    private func board() -> NSPasteboard { NSPasteboard(name: .init(UUID().uuidString)) }

    @Test func tracksNewTextLinksAndDeduplicatesWithoutReadingInitialContent() async throws {
        let root = directory(), pasteboard = board()
        defer { try? FileManager.default.removeItem(at: root); pasteboard.releaseGlobally() }
        pasteboard.setString("Before launch", forType: .string)
        let store = ClipboardStore(directory: root, pasteboard: pasteboard)
        store.start()
        defer { store.stop() }
        await store.captureChange()
        #expect(store.entries.isEmpty)
        pasteboard.clearContents(); pasteboard.setString("Meeting notes", forType: .string)
        await store.captureChange()
        pasteboard.clearContents(); pasteboard.setString("https://example.com/article", forType: .string)
        await store.captureChange()
        #expect(store.entries.map(\.kind) == [.link, .text])
        pasteboard.clearContents(); pasteboard.setString("Meeting notes", forType: .string)
        await store.captureChange()
        #expect(store.entries.count == 2)
        #expect(store.entries.first?.text == "Meeting notes")
        let reopened = ClipboardStore(directory: root, pasteboard: pasteboard)
        #expect(reopened.entries == store.entries)
    }

    @Test func rejectsConcealedTransientPasswordAndOwnScreenshotMarkers() async throws {
        let root = directory(), pasteboard = board()
        defer { try? FileManager.default.removeItem(at: root); pasteboard.releaseGlobally() }
        let store = ClipboardStore(directory: root, pasteboard: pasteboard)
        store.start()
        defer { store.stop() }
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "io.github.cezarprox.brim.screenshot"] {
            pasteboard.clearContents()
            pasteboard.setString("secret", forType: .string)
            pasteboard.setData(Data(), forType: .init(marker))
            await store.captureChange()
        }
        #expect(store.entries.isEmpty)
        #expect(ClipboardStore(directory: root, pasteboard: pasteboard).entries.isEmpty)
    }

    @Test func boundsTextCountAndTotalBytesAndKeepsUnrelatedFiles() async throws {
        let root = directory(), pasteboard = board()
        defer { try? FileManager.default.removeItem(at: root); pasteboard.releaseGlobally() }
        let store = ClipboardStore(directory: root, pasteboard: pasteboard, maxCount: 2, maxBytes: 8, maxTextBytes: 6)
        store.start()
        defer { store.stop() }
        for text in ["too long", "aaaa", "bbbb", "cccc"] {
            pasteboard.clearContents(); pasteboard.setString(text, forType: .string)
            await store.captureChange()
        }
        #expect(store.entries.compactMap(\.text) == ["cccc", "bbbb"])
        let unrelated = root.appendingPathComponent("keep.txt")
        try Data().write(to: unrelated)
        store.clear()
        #expect(store.entries.isEmpty)
        #expect(FileManager.default.fileExists(atPath: unrelated.path))
        let mode = try FileManager.default.attributesOfItem(atPath: root.path)[.posixPermissions] as? NSNumber
        #expect(mode?.intValue == 0o700)
    }

    @Test func storesImageThumbnailAndCopiesOriginalPixels() async throws {
        let root = directory(), pasteboard = board()
        defer { try? FileManager.default.removeItem(at: root); pasteboard.releaseGlobally() }
        let store = ClipboardStore(directory: root, pasteboard: pasteboard)
        store.start()
        defer { store.stop() }
        let context = try #require(CGContext(data: nil, width: 40, height: 20, bitsPerComponent: 8,
            bytesPerRow: 0, space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        context.setFillColor(NSColor.red.cgColor); context.fill(CGRect(x: 0, y: 0, width: 40, height: 20))
        let image = NSImage(cgImage: try #require(context.makeImage()), size: .zero)
        pasteboard.clearContents(); pasteboard.setData(try ImageEncoder.pngDataPreservingAlpha(from: image), forType: .png)
        await store.captureChange()
        let entry = try #require(store.entries.first)
        #expect(entry.kind == .image)
        #expect(entry.pixelSize == "40 × 20")
        #expect(store.thumbnail(for: entry) != nil)
        #expect(store.copy(entry))
        #expect(pasteboard.data(forType: .png) != nil)
        await store.captureChange()
        #expect(store.entries.count == 1)
        store.remove(entry)
        #expect(store.entries.isEmpty)
    }

    @Test func pinsAndRecognizedTextPersistAndPinnedItemsSurviveEviction() async throws {
        let root = directory(), pasteboard = board()
        defer { try? FileManager.default.removeItem(at: root); pasteboard.releaseGlobally() }
        let store = ClipboardStore(directory: root, pasteboard: pasteboard, maxCount: 2,
                                   recognizeText: { _ in "Invoice 123\nTotal 42" })
        store.start()
        defer { store.stop() }

        let context = try #require(CGContext(data: nil, width: 40, height: 20, bitsPerComponent: 8,
            bytesPerRow: 0, space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        context.setFillColor(NSColor.white.cgColor)
        context.fill(CGRect(x: 0, y: 0, width: 40, height: 20))
        let image = NSImage(cgImage: try #require(context.makeImage()), size: .zero)
        pasteboard.clearContents()
        pasteboard.setData(try ImageEncoder.pngDataPreservingAlpha(from: image), forType: .png)
        await store.captureChange()
        let imageEntry = try #require(store.entries.first)
        #expect(imageEntry.ocrText == "Invoice 123\nTotal 42")
        #expect(store.setPinned(imageEntry, true))
        #expect(store.copyRecognizedText(imageEntry))
        #expect(pasteboard.string(forType: .string) == "Invoice 123\nTotal 42")

        for value in ["new one", "new two"] {
            pasteboard.clearContents()
            pasteboard.setString(value, forType: .string)
            await store.captureChange()
        }
        #expect(store.entries.count == 2)
        #expect(store.entries.contains { $0.id == imageEntry.id && $0.isPinned })
        #expect(store.entries.contains { $0.text == "new two" })

        let reopened = ClipboardStore(directory: root, pasteboard: pasteboard, maxCount: 2)
        let restored = try #require(reopened.entries.first { $0.id == imageEntry.id })
        #expect(restored.isPinned)
        #expect(restored.ocrText == "Invoice 123\nTotal 42")

        #expect(store.setPinned(try #require(store.entries.first { $0.id == imageEntry.id }), false))
        pasteboard.clearContents()
        pasteboard.setString("new three", forType: .string)
        await store.captureChange()
        #expect(store.entries.compactMap(\.text) == ["new three", "new two"])
    }

    @Test func legacyMetadataDefaultsToUnpinnedWithoutOCR() throws {
        let root = directory(), pasteboard = board()
        defer { try? FileManager.default.removeItem(at: root); pasteboard.releaseGlobally() }
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        let id = UUID()
        let legacy: [[String: Any]] = [[
            "id": id.uuidString,
            "date": Date(timeIntervalSince1970: 100).timeIntervalSinceReferenceDate,
            "kind": "text",
            "text": "Legacy note",
            "fingerprint": "legacy",
            "byteCount": 11
        ]]
        let data = try JSONSerialization.data(withJSONObject: legacy)
        // JSONDecoder's default Date strategy expects the reference-date interval used above.
        try data.write(to: root.appendingPathComponent("entries.json"))
        let store = ClipboardStore(directory: root, pasteboard: pasteboard)
        let entry = try #require(store.entries.first)
        #expect(!entry.isPinned)
        #expect(entry.ocrText == nil)
    }

    @Test func recognizedTextLimitPreservesWholeUnicodeCharacters() {
        #expect(ClipboardOCR.bounded("  \n ", maxBytes: 10) == nil)
        #expect(ClipboardOCR.bounded("ééé", maxBytes: 5) == "éé")
        #expect(ClipboardOCR.bounded(" invoice ", maxBytes: 20) == "invoice")
    }

    @Test func onlyWebURLsAreLinks() {
        #expect(ClipboardEntry.webURL("https://example.com/path") != nil)
        for value in ["javascript:alert(1)", "file:///tmp/image.png", "https://example.com has words", "https://user:password@example.com"] {
            #expect(ClipboardEntry.webURL(value) == nil)
        }
    }

    @Test func markerOnAnotherPasteboardItemSuppressesWholeCopy() async {
        let root = directory(), pasteboard = board()
        defer { try? FileManager.default.removeItem(at: root); pasteboard.releaseGlobally() }
        let store = ClipboardStore(directory: root, pasteboard: pasteboard)
        store.start()
        defer { store.stop() }
        let first = NSPasteboardItem(), second = NSPasteboardItem()
        first.setString("Do not retain", forType: .string)
        second.setData(Data(), forType: .init("org.nspasteboard.ConcealedType"))
        pasteboard.clearContents(); pasteboard.writeObjects([first, second])
        await store.captureChange()
        #expect(store.entries.isEmpty)
    }

    @Test func resumedMonitoringIgnoresCopiesMadeWhilePaused() async {
        let root = directory(), pasteboard = board()
        defer { try? FileManager.default.removeItem(at: root); pasteboard.releaseGlobally() }
        let store = ClipboardStore(directory: root, pasteboard: pasteboard)
        store.start()
        defer { store.stop() }
        store.start(); store.stop()
        pasteboard.clearContents(); pasteboard.setString("While paused", forType: .string)
        store.start()
        await store.captureChange()
        #expect(store.entries.isEmpty)
        #expect(store.isMonitoring)
        store.stop()
    }

    @Test func pausedQueuedCaptureCannotReadOrPersistNewContent() async {
        let root = directory(), pasteboard = board()
        defer { try? FileManager.default.removeItem(at: root); pasteboard.releaseGlobally() }
        let store = ClipboardStore(directory: root, pasteboard: pasteboard)
        store.start()
        defer { store.stop() }
        pasteboard.clearContents(); pasteboard.setString("Retain this", forType: .string)
        await store.captureChange()
        store.stop()
        pasteboard.clearContents(); pasteboard.setString("Private copy while paused", forType: .string)
        // This is the same entry point an already-queued Timer task invokes after stop().
        await store.captureChange()
        #expect(store.entries.compactMap(\.text) == ["Retain this"])
        #expect(!store.isMonitoring)
        #expect(ClipboardStore(directory: root, pasteboard: pasteboard).entries.compactMap(\.text) == ["Retain this"])
    }

    @Test func failedMetadataCommitKeepsExistingHistory() async throws {
        let root = directory(), pasteboard = board()
        defer { try? FileManager.default.removeItem(at: root); pasteboard.releaseGlobally() }
        let store = ClipboardStore(directory: root, pasteboard: pasteboard)
        store.start()
        defer { store.stop() }
        pasteboard.clearContents(); pasteboard.setString("Keep me", forType: .string)
        await store.captureChange()
        let entry = try #require(store.entries.first)
        let metadata = root.appendingPathComponent("entries.json")
        try FileManager.default.removeItem(at: metadata)
        try FileManager.default.createDirectory(at: metadata, withIntermediateDirectories: false)
        pasteboard.clearContents(); pasteboard.setString("Cannot commit", forType: .string)
        await store.captureChange()
        #expect(store.entries == [entry])
        #expect(store.errorMessage != nil)
        store.clear()
        #expect(store.entries == [entry])
    }

    @Test func validEscapedTextHistoryLargerThanTwelveMegabytesReloads() throws {
        let root = directory(), pasteboard = board()
        defer { try? FileManager.default.removeItem(at: root); pasteboard.releaseGlobally() }
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        let text = String(repeating: "\u{0001}", count: 100_000)
        let values = (0..<21).map { index in
            ClipboardEntry(id: UUID(), date: Date(timeIntervalSince1970: Double(index)), kind: .text,
                           text: text, fingerprint: "fixture-\(index)", byteCount: text.utf8.count, pixelSize: nil)
        }
        let encoded = try JSONEncoder().encode(values)
        #expect(encoded.count > 12_000_000)
        try encoded.write(to: root.appendingPathComponent("entries.json"))
        let store = ClipboardStore(directory: root, pasteboard: pasteboard)
        #expect(store.entries.count == 21)
        #expect(store.errorMessage == nil)
    }
}
